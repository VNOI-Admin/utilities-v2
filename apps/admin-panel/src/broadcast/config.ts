export type VisualConfig = ReturnType<typeof derive>;

export function buildVisual(overrides: Record<string, unknown> = {}): VisualConfig {
  const base = { ...VISUAL_BASE };
  for (const key of Object.keys(VISUAL_BASE) as (keyof VisualBase)[]) {
    if (typeof overrides[key] === 'string') base[key] = overrides[key] as string;
  }
  return { ...derive(base), ...overrides } as VisualConfig;
}

export function isDarkText(hex: string): boolean {
  const value = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => Number.parseInt(value.slice(i, i + 2), 16));
  return (r * 299 + g * 587 + b * 114) / 1000 > 128;
}
